// Builds the static site into public/ (or $OUT_DIR): one HTML file per page,
// the browser modules under a content-hashed /assets/<hash>/ folder, plus
// sitemap.xml, robots.txt and _headers. Run: node build/build.mjs

import { readFile, writeFile, mkdir, rm, readdir, stat, copyFile } from 'node:fs/promises'
import { createHash } from 'node:crypto'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { loadData, toClient } from './data.mjs'
import * as T from './templates.mjs'

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')

async function listFiles(dir) {
  const out = []
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const p = path.join(dir, entry.name)
    if (entry.isDirectory()) out.push(...await listFiles(p))
    else out.push(p)
  }
  return out.sort()
}

async function exists(p) {
  try { await stat(p); return true } catch { return false }
}

export async function build({ outDir = process.env.OUT_DIR ? path.resolve(process.env.OUT_DIR) : path.join(ROOT, 'public'), quiet = false } = {}) {
  const { site, categories, objects } = await loadData(ROOT)
  const clientObjects = objects.map(toClient)

  // Browser assets, fingerprinted as one folder so relative imports keep working
  // and everything under /assets/ can be cached forever.
  const assetFiles = []
  for (const f of await listFiles(path.join(ROOT, 'src/lib'))) assetFiles.push([`lib/${path.basename(f)}`, await readFile(f)])
  for (const f of await listFiles(path.join(ROOT, 'src/client'))) assetFiles.push([`client/${path.basename(f)}`, await readFile(f)])
  assetFiles.push(['site.css', await readFile(path.join(ROOT, 'src/styles/site.css'))])
  const dataJs = `// Generated by build/build.mjs from data/. Do not edit.\n` +
    `export const OBJECTS = ${JSON.stringify(clientObjects)}\n` +
    `export const CATEGORIES = ${JSON.stringify(categories.map(({ slug, name, singular }) => ({ slug, name, singular })))}\n`
  assetFiles.push(['data.js', Buffer.from(dataJs)])
  const hash = createHash('sha256')
  for (const [name, buf] of assetFiles) hash.update(name).update(buf)
  const assetHash = hash.digest('hex').slice(0, 10)
  const assets = `/assets/${assetHash}`

  await rm(outDir, { recursive: true, force: true })
  await mkdir(outDir, { recursive: true })
  const write = async (rel, content) => {
    const p = path.join(outDir, rel)
    await mkdir(path.dirname(p), { recursive: true })
    await writeFile(p, content)
  }
  for (const [name, buf] of assetFiles) await write(`assets/${assetHash}/${name}`, buf)

  // Static files copied as they are (favicon, Open Graph images).
  const staticDir = path.join(ROOT, 'static')
  if (await exists(staticDir)) {
    for (const f of await listFiles(staticDir)) {
      const rel = path.relative(staticDir, f)
      await mkdir(path.dirname(path.join(outDir, rel)), { recursive: true })
      await copyFile(f, path.join(outDir, rel))
    }
  }
  const ogFiles = new Set((await exists(path.join(staticDir, 'og'))) ? (await readdir(path.join(staticDir, 'og'))) : [])

  const ctx = {
    site, categories, objects, clientObjects, assets,
    clientBySlug: Object.fromEntries(clientObjects.map(o => [o.slug, o])),
    categoryBySlug: Object.fromEntries(categories.map(c => [c.slug, c])),
    ogDefault: ogFiles.has('default.png') ? '/og/default.png' : null,
    ogFor: slug => (ogFiles.has(`${slug}.png`) ? `/og/${slug}.png` : null),
  }

  const pages = [
    ['index.html', T.homePage(ctx), '/'],
    ['objects.html', T.objectsIndexPage(ctx), '/objects'],
    ['compare.html', T.comparePage(ctx), '/compare'],
    ['measure.html', T.measurePage(ctx), '/measure'],
    ['about.html', T.aboutPage(ctx), '/about'],
    ['search.html', T.searchPage(ctx), null],
    ['404.html', T.notFoundPage(ctx), null],
  ]
  for (const c of categories) pages.push([`category/${c.slug}.html`, T.categoryPage(ctx, c), `/category/${c.slug}`])
  for (const o of objects) pages.push([`objects/${o.slug}.html`, T.objectPage(ctx, o), `/objects/${o.slug}`])
  for (const [file, html] of pages) await write(file, html)

  const urls = pages.filter(p => p[2]).map(p => p[2])
  await write('sitemap.xml', `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${urls.map(u => `  <url><loc>${site.url}${u === '/' ? '/' : u}</loc><lastmod>${site.updated}</lastmod></url>`).join('\n')}
</urlset>
`)
  await write('robots.txt', `User-agent: *\nAllow: /\n\nSitemap: ${site.url}/sitemap.xml\n`)
  await write('_headers', `/*
  X-Content-Type-Options: nosniff
  Referrer-Policy: strict-origin-when-cross-origin
  X-Frame-Options: DENY
  Permissions-Policy: camera=(), microphone=(), geolocation=(), payment=(), usb=()
  Content-Security-Policy: default-src 'self'; script-src 'self'; style-src 'self'; img-src 'self' data:; font-src 'self'; connect-src 'self'; object-src 'none'; base-uri 'self'; form-action 'self'; frame-ancestors 'none'

/assets/*
  Cache-Control: public, max-age=31536000, immutable
`)
  if (!quiet) console.log(`Built ${pages.length} pages (${objects.length} objects, ${categories.length} categories) into ${path.relative(ROOT, outDir) || outDir} with assets ${assets}`)
  return { pages: pages.length, objects: objects.length, categories: categories.length, assetHash, outDir, urls }
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  build().catch(err => {
    console.error(err.message)
    process.exit(1)
  })
}
